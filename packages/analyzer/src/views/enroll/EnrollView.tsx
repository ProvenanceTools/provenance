/**
 * EnrollView — the student's enrollment page, at identity `format_version` 2.1.
 *
 * Route: `/enroll` (RequireAuth, no AppShell). The first page in this analyzer
 * a student rather than course staff can reach, and the only way a student
 * obtains a credential.
 *
 * ## There is no course or semester on this page
 *
 * It previously posted to `POST /semesters/:id/enrollment` and took the
 * semester from `?semester=<uuid>`. That route is gone from the server, and the
 * page now posts to `POST /api/v1/identity/credential`, which takes no path
 * parameter at all: a 2.1 credential names no course, no semester, and no
 * assignment. One credential serves every course forever.
 *
 * ## Coming back is normal — that is how a second machine is set up
 *
 * A student who works on a laptop and a desktop enrols BOTH here. Each machine
 * generates its own master secret and its own keypair; signing in with the same
 * account returns the same global `student_ref`; each machine gets its own
 * credential over that shared ref. Contributor resolution groups on the ref, so
 * both machines are one person and the student can swap freely.
 *
 * The page must therefore never read like a duplicate warning on a return
 * visit. `reissued` alone cannot tell "added a machine" from "asked the same
 * machine for another credential", so the copy is driven by `machine_count` and
 * `key_first_issued` instead — see {@link describeIssuance}.
 *
 * The corollary for the copy at the bottom of the page: "Back Up / Restore
 * Student Identity Secret" is a BACKUP, not the second-machine path. Telling a
 * student to hand-carry the one value that can sign as them, for a flow that
 * does not need it, is a real harm dressed up as a tip.
 *
 * So the semester input is not merely unused, it would be misleading — there is
 * nothing to scope, and a `?semester=` query param is now silently irrelevant
 * rather than wrong. Course membership is answered later, from the roster, by
 * the server, against data it owns; requiring it up front was the deadlock that
 * identity 2.1 exists to remove.
 *
 * ## The private key is not here, and cannot be
 *
 * The student's master secret and private key are generated by, and never
 * leave, their recorder (`identity/secret-store.ts`). This page handles a PUBLIC
 * key on the way in and a signed credential on the way out; there is no code
 * path here that generates, derives, receives or transmits private key
 * material, and there must never be one. §5a: "there is no server-side key
 * store to breach" — a browser form that touched a private key would quietly
 * undo that.
 *
 * The uncomfortable corollary: a student master secret is ALSO 64 lowercase hex
 * characters, so the VALUE cannot be told from a public key by inspection, here
 * or on the server. Two defences, both partial and both necessary:
 * `normalizeStudentPubkey` refuses a paste carrying the recorder's
 * secret-export marker or its prose, and the warning beside the input covers
 * the student who strips the marker by hand.
 *
 * ## Both hops are checked before the student leaves
 *
 * A key that is one character short, and a credential that lost its last brace,
 * are the same class of failure: text moved by hand between two apps. Step 1
 * validates the key locally before spending a request on it; step 2 offers to
 * re-check what the student actually pasted, using the exact log-core parsers
 * the recorder uses (see `enrollment-token.ts`). Neither is decoration — a
 * mangled paste that fails silently costs a student their attribution and is
 * discovered, if ever, during an integrity investigation.
 */

