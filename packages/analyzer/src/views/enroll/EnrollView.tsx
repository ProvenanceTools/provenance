// ---------------------------------------------------------------------------
// Success presentation
// ---------------------------------------------------------------------------

/**
 * What the green panel says, chosen by what actually happened to this student's
 * machines rather than by the bare `reissued` flag.
 *
 * `reissued` is true whenever the account has enrolled before, which is exactly
 * what a student legitimately doing the supported thing — setting up a second
 * machine — will see. Presenting that as "you have already enrolled" alarms
 * them about the one flow we want to be routine. So the page speaks in machines
 * instead, using the two fields that can tell the cases apart:
 *
 *  - `key_first_issued` — this key had never been issued before, i.e. a machine
 *    being set up for the first time;
 *  - `machine_count` — how many distinct keys this student has enrolled, which
 *    is one per machine because each machine derives its own.
 *
 * The count can under-report on an account that enrolled before the server
 * started keeping a history, and over-report for a student who lost their
 * secret and re-derived on the SAME machine. Both are harmless here: the number
 * is context in a reassuring sentence, not a claim anyone acts on.
 */
export function describeIssuance(response: StudentCredentialResponse): string {
  if (!response.key_first_issued) {
    return (
      'This machine was already set up, so this is simply a fresh credential for it. The one ' +
      'you had before still works until it expires — nothing you have already recorded is ' +
      'affected.'
    );
  }
  if (response.machine_count > 1) {
    return (
      `That is ${response.machine_count} machines set up on this account. Each machine has its ` +
      'own credential and your other ones keep working — all of them are you, under the same ' +
      'ref, so your work is never split between two people.'
    );
  }
  return (
    'Copy it into VS Code with "Provenance: Import Enrollment Token". This credential works ' +
    'for every course. Setting up another machine later? Just come back here and do this ' +
    'again — that is the normal way to add one.'
  );
}

// ---------------------------------------------------------------------------
// Failure presentation
// ---------------------------------------------------------------------------

export interface MintFailure {
  /** One line naming what went wrong, in the student's terms. */
  readonly title: string;
  /** What to do about it. Always actionable — never "contact support". */
  readonly detail: string;
}

/**
 * Turn an issue failure into something a student can act on.
 *
 * Every branch here corresponds to a real, reachable response from
 * `POST /api/v1/identity/credential` (see
 * `packages/server/src/api/v1/routes/credential.ts` and `errors.ts`). The
 * catch-all at the end covers the case with no server response at all — the
 * campus wifi dropping mid-request — which `apiFetch` surfaces as a raw
 * `TypeError` from `fetch`, not as an `ApiError`.
 *
 * There is deliberately NO roster branch, and there must not be one: a roster
 * precondition is exactly the deadlock identity 2.1 removes, and the route has
 * no roster check to fail. `NOT_FOUND` is gone for the same structural reason —
 * the path carries no semester id, so there is nothing to 404.
 *
 * Deliberately does NOT echo `err.message` for the mapped codes. The server's
 * wording is written for an API consumer; a student needs to know which of the
 * plausible causes applies to them and what to do next.
 */
export function describeMintError(err: unknown): MintFailure {
  if (err instanceof UnauthorizedError) {
    return {
      title: 'Your session expired',
      detail: 'Sign in again, then come back to this page and re-paste your key.',
    };
  }

  if (err instanceof ApiError) {
    switch (err.code) {
      case 'CREDENTIAL_UNAVAILABLE':
        return {
          title: 'Your institution is not ready to issue credentials yet',
          detail:
            'The signing key for your institution is not configured, or its certificate has ' +
            'lapsed. This is not something you can fix — tell your course staff, and keep ' +
            'working in the meantime. Your recorder still records without a credential; you ' +
            'can import one later.',
        };
      case 'CREDENTIAL_SESSION_REQUIRED':
        return {
          title: 'This needs an interactive login',
          detail:
            'This page must be used with a normal Google sign-in. An API token cannot issue a ' +
            'credential, because the credential is the claim that the work is yours.',
        };
      case 'VIEW_AS_READ_ONLY':
        return {
          title: 'Credentials cannot be issued while viewing as another user',
          detail:
            'Exit view-as and sign in as yourself. A credential issued under an impersonated ' +
            'account would attribute work to someone by an operator’s action, which is exactly ' +
            'what this chain exists to make impossible.',
        };
      case 'VALIDATION':
        return {
          title: 'The server rejected that key',
          detail:
            'Copy the key again with "Provenance: Show My Enrollment Key" and paste it without ' +
            'editing it.',
        };
      case 'RATE_LIMITED':
        return {
          title: 'Too many attempts',
          detail: 'Wait a minute and try again.',
        };
      default:
        return {
          title: 'The server could not issue a credential',
          detail: `${err.message} If this keeps happening, tell your course staff.`,
        };
    }
  }

  return {
    title: 'Could not reach the server',
    detail:
      'Check your connection and try again. Nothing was issued, so it is safe to press the ' +
      'button again.',
  };
}

