/**
 * End-to-end composition proof for Manifest 2.0.
 *
 * Every other suite in this repo verifies ONE seam: log-core proves
 * `verifyManifestChain` walks root → cert → manifest; `bundle-manifest.test.ts`
 * proves `verifyBundleTrustChain` adds the two bundle-level bindings;
 * `policy-gating.test.ts` proves each heuristic honours a policy handed to it.
 * Nothing proved that a bundle produced the way a recorder produces one — real
 * ed25519 keys, a real hash chain, a real ZIP, the real loader — survives the
 * whole pipeline.
 *
 * That gap matters most for **validation check 2**. It used to compare
 * `manifest_sig` across sessions for equality; it now claims to walk
 * root → course cert → manifest → session entirely offline. If that walk is
 * wrong the failure mode is a system that reports genuine bundles as forged, or
 * forged bundles as genuine.
 *
 * Every case here therefore goes through `buildTestBundle` → a real ZIP →
 * `loadBundle` → `runValidation` / `buildIndex` + `runHeuristics`, with no
 * stubbing of the signature path, and asserts the specific check **id** and
 * **status** rather than "validation failed". A test that passes because
 * something else broke is worse than no test.
 *
 * Determinism: all keys come from fixed seeds via `buildTrustChainKeys`, all
 * walls/`t` values are generated by `buildTestBundle` from a fixed epoch, and
 * nothing here reads `Date.now()` or `Math.random()`.
 */

