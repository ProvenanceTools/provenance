describe('policy suppression and the hash chain', () => {
  it('renumbers around suppressed events: no seq hole, checks 3 and 4 both pass', async () => {
    const manifest = await buildManifest2({
      keys,
      courseId: COURSE_ID,
      filesUnderReview: [FILE],
      policy: { capture: { selection_change: false, focus_change: false, terminal: false } },
    });
    const policy = resolveCapturePolicy(manifest.policy);

    const full = studentSession();
    const kept = applyCapturePolicy(full, policy);
    // Something must actually have been dropped, or this proves nothing.
    expect(kept.length).toBeLessThan(full.length);
    expect(kept.some((e) => e.kind.startsWith('terminal.'))).toBe(false);
    expect(kept.some((e) => e.kind === 'selection.change')).toBe(false);
    expect(kept.some((e) => e.kind === 'focus.change')).toBe(false);

    const bundle = await buildBundle({
      sessions: [{ sessionStart: sessionStart2(manifest), events: kept }],
      submissionFiles: [{ path: FILE, status: 'present', content: CODE }],
    });

    // session.start plus every surviving event, numbered 0..n-1 with no gap.
    const seqs = bundle.sessions[0]!.events.map((e) => e.seq);
    expect(seqs).toEqual(Array.from({ length: kept.length + 1 }, (_, i) => i));

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });
    expect(check(report, 'chain_integrity').status).toBe('pass');
    expect(check(report, 'seq_gaps').status).toBe('pass');
    expect(statuses(report)).toEqual(ALL_PASS);
  });

  it('control: a real hole in the same stream is caught by check 4', async () => {
    // Proves the assertion above can fail. Dropping an entry AFTER chaining is
    // what a deletion looks like, and it must not be confusable with a
    // policy-suppressed event.
    const manifest = await buildManifest2({
      keys,
      courseId: COURSE_ID,
      filesUnderReview: [FILE],
      policy: { capture: { selection_change: false, focus_change: false, terminal: false } },
    });
    const policy = resolveCapturePolicy(manifest.policy);
    const kept = applyCapturePolicy(studentSession(), policy);

    const bundle = await buildBundle({
      sessions: [{ sessionStart: sessionStart2(manifest), events: kept }],
      submissionFiles: [{ path: FILE, status: 'present', content: CODE }],
      tamper: { addSeqGap: { sessionIndex: 0, afterEntryIndex: 1 } },
    });

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });
    expect(check(report, 'seq_gaps').status).toBe('fail');
    // The trust chain is untouched by a deleted entry.
    expect(check(report, 'session_binding').status).toBe('pass');
  });
});
