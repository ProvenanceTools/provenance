describe('a genuine Manifest 2.0 bundle', () => {
  it('passes all eight validation checks, check 2 walking root → cert → manifest → session', async () => {
    const manifest = await buildManifest2({
      keys,
      courseId: COURSE_ID,
      assignmentId: ASSIGNMENT_ID,
      semester: SEMESTER,
      issuedAt: ISSUED_AT,
      filesUnderReview: [FILE],
      policy: { capture: { selection_change: true, focus_change: true, terminal: true } },
    });
    const bundle = await build20Bundle(manifest);

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });

    expect(statuses(report)).toEqual(ALL_PASS);
    expect(report.overall).toBe('pass');

    // Check 2 must have taken the CHAIN path, not the legacy sig-equality one.
    const binding = check(report, 'session_binding');
    expect(binding.detail).toContain('Trust chain verified offline');
    expect(binding.detail).toContain(`root → course_cert (${COURSE_ID}) → manifest`);
    expect(binding.detail).toContain(`certificate valid at issue time (${ISSUED_AT})`);

    const summary = await summarizeBundleManifest(bundle, keys.rootPubkeyHex);
    expect(summary.format_version).toBe('2.0');
    expect(summary.trust_chain).toBe('verified');
    expect(summary.cert?.course_pubkey).toBe(keys.coursePubkeyHex);
    expect(summary.cert?.in_window).toBe(true);
    expect(summary.disabled_signals).toEqual([]);
  });

  it('reports check 2 as skipped — never pass — when no root key is configured', async () => {
    // The chain walk genuinely consumes the root key. Without one there is no
    // statement to make, and inventing either verdict would be worse than none.
    const manifest = await buildManifest2({ keys, courseId: COURSE_ID, filesUnderReview: [FILE] });
    const bundle = await build20Bundle(manifest);

    const report = await runValidation(bundle);

    expect(check(report, 'session_binding').status).toBe('skipped');
    expect(check(report, 'session_binding').detail).toContain('no root public key');
    expect(report.overall).toBe('warn');
  });
});

