// 3. Tampering is caught per link, each failing for the right reason.
// ---------------------------------------------------------------------------

describe('trust-chain tampering', () => {
  it('rejects a course_cert the root never signed', async () => {
    // Same course key, but the certificate is signed by a root the analyzer
    // does not trust.
    const rogueRoot = await buildTrustChainKeys(0x99, 0x22);
    const manifest = await buildManifest2({
      keys: rogueRoot,
      courseId: COURSE_ID,
      filesUnderReview: [FILE],
    });
    const bundle = await build20Bundle(manifest);

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });

    expectOnlySessionBindingFailed(report);
    expect(check(report, 'session_binding').detail).toContain(
      'course_cert does not verify against the root public key',
    );
  });

  it('rejects a manifest signed by a course key the root never certified', async () => {
    // The certificate is genuine (root-signed, vouching for the real course
    // key) — but the manifest payload was signed by a different key entirely.
    // Step 1 passes; step 2 must catch it.
    const rogueCourse = await buildTrustChainKeys(0x11, 0x77);
    const manifest = await buildManifest2({
      keys: { ...keys, coursePrivkey: rogueCourse.coursePrivkey },
      courseId: COURSE_ID,
      filesUnderReview: [FILE],
    });
    expect(manifest.course_cert?.course_pubkey).toBe(keys.coursePubkeyHex);
    await expect(
      verifyCourseCert(manifest.course_cert as CourseCert, keys.rootPubkeyHex),
    ).resolves.toMatchObject({ ok: true });

    const bundle = await build20Bundle(manifest);
    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });

    expectOnlySessionBindingFailed(report);
    expect(check(report, 'session_binding').detail).toContain(
      'manifest payload does not verify against the certified course public key',
    );
  });

  it('rejects a manifest whose course_id disagrees with its certificate', async () => {
    // 61B's key signing a manifest that claims to be 61C. Both signatures are
    // genuine; only comparing the two ids catches it.
    const manifest = await buildManifest2({
      keys,
      courseId: 'berkeley-cs61c',
      certCourseId: COURSE_ID,
      filesUnderReview: [FILE],
    });
    const bundle = await build20Bundle(manifest);

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });

    expectOnlySessionBindingFailed(report);
    expect(check(report, 'session_binding').detail).toContain(
      `manifest course_id berkeley-cs61c does not match certificate course_id ${COURSE_ID}`,
    );
  });

  it('rejects a policy block edited after signing — the student off-switch attempt', async () => {
    const genuine = await buildManifest2({
      keys,
      courseId: COURSE_ID,
      filesUnderReview: [FILE],
      policy: { capture: { selection_change: true, focus_change: true, terminal: true } },
    });

    // Control: the untouched manifest verifies. Everything below differs from
    // this by exactly one boolean inside `policy`.
    const cleanReport = await runValidation(await build20Bundle(genuine), {
      rootPubkeyHex: keys.rootPubkeyHex,
    });
    expect(statuses(cleanReport)).toEqual(ALL_PASS);

    const edited: Manifest = {
      ...genuine,
      policy: { capture: { selection_change: true, focus_change: true, terminal: false } },
    };
    const bundle = await build20Bundle(edited);
    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });

    expectOnlySessionBindingFailed(report);
    expect(check(report, 'session_binding').detail).toContain(
      'manifest payload does not verify against the certified course public key',
    );
    // And the summary must not present the edited policy as course-sanctioned.
    const summary = await summarizeBundleManifest(bundle, keys.rootPubkeyHex);
    expect(summary.trust_chain).toBe('invalid');
    expect(summary.trust_chain_detail).toContain('certified course public key');
    expect(summary.cert?.in_window).toBe(false);
    expect(summary.cert?.window_reason).toBe('unverified');
  });

  it("rejects a session whose manifest_sig is not the embedded manifest's sig", async () => {
    // `manifest_sig` is the HKDF input keying material for the session keypair,
    // so this equality is what binds the VERIFIED manifest to the key that
    // signed this session's checkpoints and the bundle seal. The override is
    // applied before chaining, so the hash chain stays intact and check 2 is
    // the only thing that can catch it.
    const manifest = await buildManifest2({ keys, courseId: COURSE_ID, filesUnderReview: [FILE] });
    const strangerSig = 'b'.repeat(128);
    const bundle = await build20Bundle(manifest, [
      { events: studentSession() },
      { events: continuationSession(), sessionStart: { manifest_sig: strangerSig } },
    ]);

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });

    expect(statuses(report)).toEqual({
      ...ALL_PASS,
      session_binding: 'fail',
      // The second session ends at CODE_APPENDED, which is not what was submitted.
      submitted_code_match: 'fail',
    });
    const binding = check(report, 'session_binding');
    expect(binding.detail).toContain(`recorded manifest_sig ${strangerSig.slice(0, 16)}…`);
    expect(binding.detail).toContain('but carries a manifest signed');
    expect(binding.supportingSeqs).toEqual([{ sessionId: bundle.sessions[1]!.sessionId, seq: 0 }]);
  });
});

// ---------------------------------------------------------------------------
// 4. The 1.x downgrade attack is refused.
//    Every signature verifies individually; the chain must still reject it.
// ---------------------------------------------------------------------------

describe('the 1.x downgrade attack', () => {
  /**
   * A genuine 1.x manifest (signed over the four 1.x fields only) with a real
   * root-signed certificate stapled on, plus an invented `policy` and the 2.0
   * capability fields — none of which the 1.x signature covers.
   */
  async function buildDowngradeManifest(): Promise<{ manifest: Manifest; cert: CourseCert }> {
    const legacyPayload = {
      assignment_id: ASSIGNMENT_ID,
      semester: SEMESTER,
      issued_at: ISSUED_AT,
      files_under_review: [FILE],
    };
    const sig = await signManifest(legacyPayload, keys.coursePrivkey);

    const certPayload: Omit<CourseCert, 'root_sig'> = {
      course_id: COURSE_ID,
      course_pubkey: keys.coursePubkeyHex,
      valid_from: '2026-08-20',
      valid_until: '2027-01-15',
    };
    const cert: CourseCert = {
      ...certPayload,
      root_sig: await signCourseCert(certPayload, keys.rootPrivkey),
    };

    return {
      cert,
      manifest: {
        // No `format_version` at all — this is what a 1.x manifest looks like.
        ...legacyPayload,
        sig,
        course_id: COURSE_ID,
        collaboration: 'solo',
        submission: 'bundle',
        scope: 'directory',
        // The prize: capture switched off by a block nobody signed.
        policy: { capture: { selection_change: false, focus_change: false, terminal: false } },
        course_cert: cert,
      },
    };
  }

  it('has every individual signature verify — which is exactly why step 0 must exist', async () => {
    const { manifest, cert } = await buildDowngradeManifest();

    await expect(verifyCourseCert(cert, keys.rootPubkeyHex)).resolves.toMatchObject({ ok: true });
    await expect(verifyManifest(manifest, keys.coursePubkeyHex)).resolves.toMatchObject({
      ok: true,
    });
  });

  it('fails check 2 on format_version, not on any signature', async () => {
    const { manifest } = await buildDowngradeManifest();
    const bundle = await build20Bundle(manifest);

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });

    expectOnlySessionBindingFailed(report);
    expect(check(report, 'session_binding').detail).toContain(
      'manifest is format_version 1.0, not 2.0',
    );
    expect(check(report, 'session_binding').detail).not.toContain('signature');
  });

  it('does not hand the student the capture off-switch it was reaching for', async () => {
    const { manifest } = await buildDowngradeManifest();
    const bundle = await build20Bundle(manifest, [{ events: terminalHeavySession() }]);

    // The unsigned `policy` never becomes an effective policy: at 1.x the field
    // is not part of the manifest schema at all, so it is dropped on parse.
    const resolved = resolveBundleCapturePolicy(bundle);
    expect(resolved.disabledSignals).toEqual([]);
    expect(isSignalCaptured(bundle, 'terminal')).toBe(true);

    // …and the terminal heuristics it was meant to silence still fire.
    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });
    const fired = new Set(
      runHeuristics(buildIndex(bundle), bundle, report).map((f) => f.heuristic),
    );
    for (const id of TERMINAL_HEURISTICS) expect(fired).toContain(id);
  });
});

// ---------------------------------------------------------------------------
// 5. The absence-vs-disabled rule holds end to end.
// ---------------------------------------------------------------------------

describe('a signed policy that disables terminal capture', () => {
  const TERMINAL_OFF = { capture: { selection_change: true, focus_change: true, terminal: false } };

  async function terminalOffManifest(): Promise<Manifest> {
    return buildManifest2({
      keys,
      courseId: COURSE_ID,
      assignmentId: ASSIGNMENT_ID,
      semester: SEMESTER,
      issuedAt: ISSUED_AT,
      filesUnderReview: [FILE],
      policy: TERMINAL_OFF,
    });
  }

  /** Build the bundle a policy-honouring recorder would actually have written. */
  async function buildSuppressedBundle(): Promise<{ manifest: Manifest; bundle: Bundle }> {
    const manifest = await terminalOffManifest();
    const policy = resolveCapturePolicy(manifest.policy);
    expect(policy.terminal).toBe(false);

    const bundle = await buildBundle({
      sessions: [
        {
          sessionStart: sessionStart2(manifest),
          events: applyCapturePolicy(terminalHeavySession(), policy),
        },
      ],
    });
    return { manifest, bundle };
  }

  it('is proven signed: check 2 verifies and the summary names the disabled signal', async () => {
    const { bundle } = await buildSuppressedBundle();

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });
    expect(check(report, 'session_binding').status).toBe('pass');

    const summary = await summarizeBundleManifest(bundle, keys.rootPubkeyHex);
    expect(summary.trust_chain).toBe('verified');
    expect(summary.disabled_signals).toEqual(['terminal']);
  });

  it('makes the terminal heuristics not-applicable, where a 1.x bundle fires all three', async () => {
    // Control: the identical event stream under a 1.x bundle. If this half stops
    // producing flags the gated half below proves nothing.
    const legacy = await buildBundle({ sessions: [{ events: terminalHeavySession() }] });
    const legacyReport = await runValidation(legacy);
    const legacyFired = new Set(
      runHeuristics(buildIndex(legacy), legacy, legacyReport).map((f) => f.heuristic),
    );
    for (const id of TERMINAL_HEURISTICS) expect(legacyFired).toContain(id);

    const { bundle } = await buildSuppressedBundle();
    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });
    const gatedFired = new Set(
      runHeuristics(buildIndex(bundle), bundle, report).map((f) => f.heuristic),
    );
    for (const id of TERMINAL_HEURISTICS) expect(gatedFired).not.toContain(id);
  });

  it('gates on the policy itself, not merely on the absence of terminal events', async () => {
    // A recorder that ignored the policy (a stale build, a hostile port) would
    // still emit terminal events. The analyzer must refuse to reason about them
    // rather than reading them as evidence the course said not to collect.
    const manifest = await terminalOffManifest();
    const bundle = await buildBundle({
      sessions: [{ sessionStart: sessionStart2(manifest), events: terminalHeavySession() }],
    });
    expect(buildIndex(bundle).ordered.some((e) => e.kind.startsWith('terminal.'))).toBe(true);

    const report = await runValidation(bundle, { rootPubkeyHex: keys.rootPubkeyHex });
    expect(check(report, 'session_binding').status).toBe('pass');

    const fired = new Set(
      runHeuristics(buildIndex(bundle), bundle, report).map((f) => f.heuristic),
    );
    for (const id of TERMINAL_HEURISTICS) expect(fired).not.toContain(id);
  });

  it('makes a cross-submission comparison not-applicable rather than scoring it', async () => {
    // Two submissions with identical kind streams. Under 1.x that is a clone
    // signal; under a policy that removed a kind from both streams the
    // similarity is an artefact of the policy, so the pair must be skipped —
    // not scored zero, and certainly not flagged.
    const manifest = await terminalOffManifest();
    const policy = resolveCapturePolicy(manifest.policy);

    const legacyFeatures = await Promise.all(
      [0, 1].map(async () => {
        const b = await buildBundle({ sessions: [{ events: terminalHeavySession() }] });
        return extractCrossFeatures(b, buildIndex(b));
      }),
    );
    for (const f of legacyFeatures) expect(f.disabledCaptureSignals).toEqual([]);
    expect(
      editingPatternCloneHeuristic.run(legacyFeatures, DEFAULT_CROSS_HEURISTIC_CONFIG),
    ).toHaveLength(1);

    const gatedFeatures = await Promise.all(
      [0, 1].map(async () => {
        const b = await buildBundle({
          sessions: [
            {
              sessionStart: sessionStart2(manifest),
              events: applyCapturePolicy(terminalHeavySession(), policy),
            },
          ],
        });
        return extractCrossFeatures(b, buildIndex(b));
      }),
    );
    for (const f of gatedFeatures) expect(f.disabledCaptureSignals).toEqual(['terminal']);
    expect(editingPatternCloneHeuristic.run(gatedFeatures, DEFAULT_CROSS_HEURISTIC_CONFIG)).toEqual(
      [],
    );
  });
});

