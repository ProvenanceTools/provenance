type EventSpec = NonNullable<SessionSpec['events']>[number];

const AT_ORIGIN = { start: { line: 0, character: 0 }, end: { line: 0, character: 0 } };
/** End of `CODE` — line 2 is the empty line after the trailing newline. */
const AFTER_CODE = { start: { line: 2, character: 0 }, end: { line: 2, character: 0 } };

