/**
 * A realistic single-session work stream: open an empty file, type a solution,
 * poke around in a terminal, save.
 *
 * The terminal events are deliberately flag-worthy — `shell_integration: false`
 * plus an all-zero exit code — so that the policy-gating cases below have
 * something to suppress and the un-gated control has something to fire.
 */
function studentSession(): EventSpec[] {
  return [
    {
      kind: 'doc.open',
      data: { path: FILE, sha256: EMPTY_SHA, line_count: 0, content: EMPTY },
    },
    {
      kind: 'selection.change',
      data: { path: FILE, range: AT_ORIGIN, was_selection: false },
    },
    {
      kind: 'doc.change',
      data: { path: FILE, source: 'typed', deltas: [{ range: AT_ORIGIN, text: CODE }] },
    },
    { kind: 'focus.change', data: { gained: true } },
    {
      kind: 'terminal.open',
      data: { terminal_id: 't1', shell: '/bin/zsh', shell_integration: false },
    },
    {
      kind: 'terminal.command',
      data: { terminal_id: 't1', command: 'python hw1.py', exit_code: 0 },
    },
    { kind: 'doc.save', data: { path: FILE, sha256: CODE_SHA } },
    { kind: 'session.end', data: { reason: 'window_closed' } },
  ];
}

/** A continuation session: reopen the saved file, append a line, save again. */
function continuationSession(): EventSpec[] {
  return [
    {
      kind: 'doc.open',
      data: { path: FILE, sha256: CODE_SHA, line_count: 2, content: CODE },
    },
    {
      kind: 'doc.change',
      data: {
        path: FILE,
        source: 'typed',
        deltas: [{ range: AFTER_CODE, text: 'print(solve(21))\n' }],
      },
    },
    { kind: 'doc.save', data: { path: FILE, sha256: CODE_APPENDED_SHA } },
    { kind: 'session.end', data: { reason: 'window_closed' } },
  ];
}

/**
 * A stream that trips all three terminal-dependent heuristics under a 1.x
 * bundle: `shell_integration_disabled` (terminal.open with the flag off),
 * `no_intermediate_errors` (its shell-integration-disabled degradation), and
 * `terminal_active_during_external_change` (a terminal open before an external
 * write).
 */
function terminalHeavySession(): EventSpec[] {
  return [
    {
      kind: 'doc.open',
      data: { path: FILE, sha256: EMPTY_SHA, line_count: 0, content: EMPTY },
    },
    {
      kind: 'doc.change',
      data: { path: FILE, source: 'typed', deltas: [{ range: AT_ORIGIN, text: CODE }] },
    },
    {
      kind: 'terminal.open',
      data: { terminal_id: 't1', shell: '/bin/zsh', shell_integration: false },
    },
    {
      kind: 'terminal.command',
      data: { terminal_id: 't1', command: 'python hw1.py', exit_code: 0 },
    },
    {
      kind: 'fs.external_change',
      data: {
        path: FILE,
        old_hash: CODE_SHA,
        new_hash: FOREIGN_SHA,
        diff_size: 120,
        operation: 'modify',
      },
    },
    { kind: 'session.end', data: { reason: 'window_closed' } },
  ];
}

const TERMINAL_HEURISTICS = [
  'shell_integration_disabled',
  'no_intermediate_errors',
  'terminal_active_during_external_change',
] as const;

/**
 * Mirror of the recorder's single capture choke point
 * (`packages/recorder/src/session/session-host.ts`): suppression happens BEFORE
 * `seq` is allocated, so a dropped event consumes no seq and leaves no hole for
 * check 4 to read as a deleted entry. `buildTestBundle` numbers whatever list it
 * is handed contiguously from 0, so filtering here reproduces exactly the stream
 * a policy-configured recorder would have written.
 */
function applyCapturePolicy(events: EventSpec[], policy: CapturePolicy): EventSpec[] {
  return events.filter((e) => isEventKindCaptured(e.kind as EventKind, policy));
}

async function buildBundle(opts: BuildOpts): Promise<Bundle> {
  const { zipBuffer } = await buildTestBundle({
    assignmentId: ASSIGNMENT_ID,
    semester: SEMESTER,
    ...opts,
  });
  const loaded = await loadBundle(new Blob([zipBuffer]), 'e2e.zip');
  if (!loaded.ok) throw new Error(`bundle load failed: ${JSON.stringify(loaded.error)}`);
  return loaded.value;
}

/** A complete, submittable 2.0 bundle carrying `manifest` in every session.start. */
async function build20Bundle(
  manifest: Manifest,
  sessions: SessionSpec[] = [{ events: studentSession() }],
): Promise<Bundle> {
  const start = sessionStart2(manifest);
  return buildBundle({
    sessions: sessions.map((s) => ({
      ...s,
      sessionStart: { ...start, ...(s.sessionStart ?? {}) },
    })),
    submissionFiles: [{ path: FILE, status: 'present', content: CODE }],
  });
}

function check(report: ValidationReport, id: string): ValidationCheck {
  const found = report.checks.find((c) => c.id === id);
  if (found === undefined) throw new Error(`no check with id ${id}`);
  return found;
}

function statuses(report: ValidationReport): Record<string, string> {
  return Object.fromEntries(report.checks.map((c) => [c.id, c.status]));
}

const ALL_PASS = {
  manifest_sig: 'pass',
  session_binding: 'pass',
  chain_integrity: 'pass',
  seq_gaps: 'pass',
  monotonic_t: 'pass',
  monotonic_wall: 'pass',
  doc_save_hashes: 'pass',
  submitted_code_match: 'pass',
};

/**
 * The links that must stay green while a trust-chain tamper case fails check 2.
 * Asserting these is what makes each case fail for the RIGHT reason: a bundle
 * whose hash chain also broke would "fail validation" for a completely
 * different one.
 */
function expectOnlySessionBindingFailed(report: ValidationReport): void {
  expect(statuses(report)).toEqual({ ...ALL_PASS, session_binding: 'fail' });
}

